#!/usr/bin/env python3
"""run_pipeline.py

A minimal pipeline orchestrator that follows the file‑system state‑machine pattern
described in the Project‑Development methodology.

It expects each work item to live under ``data/<item_id>/`` with the following
optional files:

    raw.json      – acquire stage (not used in this minimal demo)
    prompt.md    – prepare stage (not used in this demo)
    response.md  – **process** stage output (LLM response)
    parsed.json   – **parse** stage output (generated by response_parser.py)
    final.html   – render stage (not implemented here)

The script walks the ``data`` directory, and for every item it:
1. Checks whether ``response.md`` exists.
2. If ``parsed.json`` is missing, invokes :pyfunc:`tools.response_parser.parse_response`
   to generate it.
3. Logs actions to ``logs/pipeline.log``.

Running the script will therefore "wire" the parser into the pipeline and
process any existing sample responses.
"""

import subprocess
import sys
from pathlib import Path
import logging

# ---------------------------------------------------------------------------
# Logging configuration – all pipeline actions go to ``logs/pipeline.log``.
# ---------------------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parents[1]
LOG_DIR = BASE_DIR / "logs"
LOG_DIR.mkdir(parents=True, exist_ok=True)
LOG_FILE = LOG_DIR / "pipeline.log"
logging.basicConfig(
    filename=str(LOG_FILE),
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
)

def run_parser(response_path: Path) -> Path:
    """Run the tolerant parser on *response_path* and return the path to the JSON.
    
    The parser is a separate script (tools/response_parser.py).  We invoke it as a
    subprocess to keep this orchestrator lightweight and to capture any error
    messages.
    """
    parser_script = BASE_DIR / "tools" / "response_parser.py"
    try:
        result = subprocess.run(
            [sys.executable, str(parser_script), str(response_path)],
            capture_output=True,
            text=True,
            check=True,
        )
        logging.info("Parsed %s successfully", response_path)
        # The parser writes a JSON file next to the response.
        return response_path.with_suffix('.json')
    except subprocess.CalledProcessError as exc:
        logging.error(
            "Parser failed for %s – returncode=%s, stderr=%s",
            response_path,
            exc.returncode,
            exc.stderr,
        )
        raise

def process_item(item_dir: Path) -> None:
    """Process a single ``data/<item_id>`` directory.
    """
    response_md = item_dir / "response.md"
    parsed_json = item_dir / "parsed.json"

    if not response_md.is_file():
        logging.warning("No response.md found in %s – skipping", item_dir)
        return

    if parsed_json.is_file():
        logging.info("parsed.json already exists for %s – skipping", item_dir)
        return

    # Run parser and generate parsed.json.
    json_path = run_parser(response_md)
    # Move the generated json (named response.json by the parser) to the expected name.
    generated = response_md.with_suffix('.json')
    if generated.is_file():
        generated.rename(parsed_json)
        logging.info("Renamed %s to %s", generated, parsed_json)
    else:
        logging.error("Parser did not produce expected JSON for %s", response_md)

def main() -> None:
    data_root = BASE_DIR / "data"
    if not data_root.is_dir():
        logging.error("Data directory %s does not exist", data_root)
        sys.exit(1)

    for item in data_root.iterdir():
        if item.is_dir():
            process_item(item)

    logging.info("Pipeline run completed.")

if __name__ == "__main__":
    main()
