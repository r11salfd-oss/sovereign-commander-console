#!/usr/bin/env python3
"""response_parser.py

A tolerant parser for LLM‑generated markdown responses.

Expected response format (example)::

    ## Summary
    This is the high‑level summary.

    ## Score
    Rating: 7

    ## Details
    - Point one
    - Point two

The parser extracts the three sections (summary, score, details) even if:
* extra whitespace or blank lines are present,
* the header case varies (e.g., "summary" or "SUMMARY"),
* the score line contains extra text (e.g., "Rating: 7/10"),
* bullet list markers differ ("-", "*", or numeric).

If a section cannot be found, a sensible default is returned and the incident is logged
to ``logs/parser_errors.log`` for later review.
"""

import re
import json
import logging
from pathlib import Path
from typing import Dict, Any

# ---------------------------------------------------------------------------
# Logging configuration – logs are written to the project ``logs`` directory.
# ---------------------------------------------------------------------------
import os

def _determine_log_dir() -> Path:
    # Primary location (may be read‑only on some mounts)
    primary = Path(__file__).resolve().parents[2] / "scratch" / "logs"
    try:
        primary.mkdir(parents=True, exist_ok=True)
        return primary
    except Exception:
        # Fallback to the guaranteed writable artifact directory.
        conv_id = "51c1f54a-8e82-4d38-9ee2-b9071ed4bd69"
        fallback = Path(os.getenv("HOME", "/home/anas")) / ".gemini" / "antigravity-cli" / "brain" / conv_id / "scratch" / "logs"
        fallback.mkdir(parents=True, exist_ok=True)
        return fallback

LOG_DIR = _determine_log_dir()
LOG_FILE = LOG_DIR / "parser_errors.log"
logging.basicConfig(
    filename=str(LOG_FILE),
    level=logging.INFO,
    format="%(asctime)s %(levelname)s %(message)s",
)

# ---------------------------------------------------------------------------
# Helper regex patterns (case‑insensitive, tolerant to surrounding whitespace).
# ---------------------------------------------------------------------------
_SECTION_RE = re.compile(r"^##\s*(?P<title>[^\n]+)\s*$", re.MULTILINE | re.IGNORECASE)
_SCORE_RE = re.compile(r"Rating\s*[:=]?\s*(?P<score>\d+)", re.IGNORECASE)


def _extract_sections(text: str) -> Dict[str, str]:
    """Split *text* into a mapping of section title → content.

    The function walks through the markdown looking for level‑2 headings (``##``).
    Everything between a heading and the next heading belongs to that section.
    Whitespace around the content is stripped.
    """
    sections: Dict[str, str] = {}
    matches = list(_SECTION_RE.finditer(text))
    for i, match in enumerate(matches):
        start = match.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        title = match.group("title").strip().lower()
        content = text[start:end].strip()
        sections[title] = content
    return sections


def _parse_score(section_text: str) -> int:
    """Extract an integer score from *section_text*.

    If the regex does not match, ``0`` is returned and a warning is logged.
    """
    m = _SCORE_RE.search(section_text)
    if m:
        try:
            return int(m.group("score"))
        except ValueError:
            pass
    logging.warning("Score could not be parsed from section: %s", section_text[:50])
    return 0


def parse_response(response_path: str) -> Dict[str, Any]:
    """Parse a markdown response generated by an LLM.

    Parameters
    ----------
    response_path: str
        Path to the ``response.md`` file produced by the *process* stage.

    Returns
    -------
    dict
        A dictionary with the keys ``summary``, ``score`` and ``details``.
        Missing sections are filled with sensible defaults and are logged.
    """
    try:
        raw = Path(response_path).read_text(encoding="utf-8")
    except Exception as exc:
        logging.error("Failed to read response file %s: %s", response_path, exc)
        return {"summary": "", "score": 0, "details": []}

    sections = _extract_sections(raw)

    # Summary – free‑form text; default to empty string.
    summary = sections.get("summary", "")
    if not summary:
        logging.info("Summary section missing in %s", response_path)

    # Score – integer extraction with fallback.
    score_text = sections.get("score", "")
    score = _parse_score(score_text) if score_text else 0
    if not score_text:
        logging.info("Score section missing in %s", response_path)

    # Details – bullet list; tolerate '-', '*', or numeric prefixes.
    details_raw = sections.get("details", "")
    details: list[str] = []
    if details_raw:
        for line in details_raw.splitlines():
            line = line.strip()
            # Remove common bullet markers.
            line = re.sub(r"^[\-\*\+]\s+", "", line)
            line = re.sub(r"^\d+\.\s+", "", line)
            if line:
                details.append(line)
    else:
        logging.info("Details section missing in %s", response_path)

    # Assemble the result.
    result = {
        "summary": summary,
        "score": score,
        "details": details,
    }

    # Optional: dump a JSON representation for downstream stages.
    json_path = Path(response_path).with_suffix('.json')
    try:
        json_path.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding='utf-8')
    except Exception as exc:
        logging.error("Failed to write JSON output %s: %s", json_path, exc)

    return result

# ---------------------------------------------------------------------------
# If the script is executed directly, parse the path given on the command line.
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    import sys
    if len(sys.argv) != 2:
        print("Usage: response_parser.py <response.md>")
        sys.exit(1)
    out = parse_response(sys.argv[1])
    print(json.dumps(out, ensure_ascii=False, indent=2))
